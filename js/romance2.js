// 화목도(0~100): 연인이 둘 이상일 때 서로를 어떻게 받아들이는지. 높으면 함께 싸울 때 힘이 나고, 낮으면 신경전
function lovers() { return G.roster.filter((u) => canRomance(u) && u.loveStage >= 4); }
function harmony() { return G.harmony == null ? 60 : G.harmony; }
function addHarmony(v) { G.harmony = clamp(harmony() + v, 0, 100); }
function harmonyBand() { const h = harmony(); return h >= 70 ? "high" : h >= 40 ? "mid" : "low"; }
const HARMONY_NAME = { high: "화목함", mid: "어색함", low: "신경전" };
// 질투를 잘 안 하는 성격
const EASYGOING = ["optimist", "chatty", "kind", "lazy"];

function loveBattleBonus(B) {
  if (!B.hero) return;
  const inParty = B.units.filter((c) => c.side === "A" && c.unit.loveStage >= 4 && canRomance(c.unit));
  const band = inParty.length >= 2 ? harmonyBand() : null;
  for (const c of B.units) {
    if (c.side !== "A" || !c.unit.loveStage) continue;
    let k = 1 + LOVE_STAGES[c.unit.loveStage].bonus;
    // 연인이 둘 이상 함께 나가면: 화목하면 서로 감싸고, 사이가 나쁘면 신경이 쓰인다
    if (band && c.unit.loveStage >= 4) k += band === "high" ? 0.03 * (inParty.length - 1) : band === "low" ? -0.04 : 0;
    for (const s of ["atk", "mag", "def", "res", "heal"]) c[s] = Math.round(c[s] * k);
  }
}

