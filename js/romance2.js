function romanceExtras(u) {
  const ls = lovers();
  const dates = u.loveStage >= 3 ? `<div class="date-row"><small>데이트 · 금화 15${canDate(u) ? "" : ` · ${3 - (G.day - u.dateDay)}일 뒤`}</small><div class="date-btns">${Object.entries(DATES).filter(([, d]) => d.need()).map(([k, d]) => `<button class="btn sm" data-act="lovedate" data-arg="${u.id}:${k}" ${canDate(u) ? "" : "disabled"}>${d.name}</button>`).join("")}</div></div>` : "";
  const harm = u.loveStage >= 4 && ls.length >= 2 ? `<small class="harm h-${harmonyBand()}">연인 ${ls.length}명 · 서로의 사이: ${HARMONY_NAME[harmonyBand()]} (${harmony()})${G.flags.loveTogether ? " · 함께하기로 약속" : ""}</small>` : "";
  return dates + harm;
}
