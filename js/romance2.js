const fillTalk = (s, u, other) => s.replace(/\{n\}/g, u.name).replace(/\{d\}/g, u.prof.dream).replace(/\{f\}/g, u.prof.food).replace(/\{o\}/g, other ? other.name : "다른 사람");
function talkTier(u) { return u.loveStage >= 4 ? 3 : u.loveStage >= 3 ? 2 : u.loveStage >= 2 ? 1 : 0; }
function talkLines(u) {
  const tier = talkTier(u), t = toneOf(u), n = u.name;
  const others = lovers().filter((x) => x !== u);
  const one = (s) => [[n, fillTalk(s, u, pick(others))]];
  if (u.loveStage >= 4 && others.length && chance(0.35)) return one(pick(TALK_RIVAL[harmonyBand()]));
  if (u.loveStage >= 2 && u.loveStage < 5 && TALK_REL[u.prof.rel] && chance(0.3)) return one(pick(TALK_REL[u.prof.rel]));
  if (chance(0.3)) return pick(CONVO[tier]).map(([w, s]) => [fillTalk(w, u), fillTalk(s, u)]);
  if (chance(0.2) && TALK_HOBBY2[u.traits.hobby]) return one(pick(TALK_HOBBY2[u.traits.hobby]));
  if (chance(0.12) && TALK_CHAPTER[G.chapter]) return one(pick(TALK_CHAPTER[G.chapter]));
  return one(pick(TALK2[t][tier]));
}
function talkLine(u) { return talkLines(u)[0][1]; }

