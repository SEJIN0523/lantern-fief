function canDate(u) { return canRomance(u) && u.loveStage >= 3 && (u.dateDay == null || G.day - u.dateDay >= 3); }
function loveDate(arg) {
  const [id, k] = arg.split(":");
  const u = unitById(id), D = DATES[k];
  if (!u || !D || !D.need()) return;
  if (!canDate(u)) return toast("데이트는 사흘에 한 번이에요");
  if (G.res.gold < 15) return toast("금화가 부족해요 (15)");
  G.res.gold -= 15; u.dateDay = G.day;
  const ups = addLove(u, rint(6, 9)).map((s) => [u, s]);
  // 다른 연인에게 들키면 화목이 조금 내려간다
  if (lovers().some((x) => x !== u) && chance(0.4)) addHarmony(-5);
  save();
  const lines = D.lines[toneOf(u)].map(([w, s]) => [fillTalk(w, u), fillTalk(s, u)]);
  playScene({ bg: k === "tavern" ? "village" : k === "hill" ? "dusk" : "village", uid: u.id, lines: [["*", `${u.name}와(과) ${D.name}`], ...lines] }, () => playLoveScenes(ups, () => { save(); showHub(); showDetail(u); }));
}

// ---------- 대화하기: 여러 줄 대화 ----------
function loveTalk(u) {
  if (u.talkDay === G.day) return toast("오늘은 이미 이야기를 나눴어요");
  u.talkDay = G.day;
  const lines = talkLines(u);
  const ups = addLove(u, rint(3, 5) + (lines.length > 1 ? 1 : 0)).map((s) => [u, s]);
  save();
  playScene({ bg: "village", lines, uid: u.id }, () => playLoveScenes(ups, () => { save(); showHub(); showDetail(u); }));
}

