function loveConfess(u) {
  if (u.loveStage !== 3 || u.love < 84) return toast("아직 마음이 충분히 깊지 않아요");
  u.loveStage = 4; save();
  const rv = rivalScene(u);
  playLoveScenes([[u, 4]], () => (rv ? playScene(rv, () => { save(); showHub(); showDetail(u); }) : (save(), showHub(), showDetail(u))));
}
// 서약: 이미 서약한 사람이 있으면 연인들 사이가 화목해야(60 이상) 받아 준다
function loveOath(u) {
  if (u.loveStage !== 4 || u.love < 100) return toast("호감도가 가득 차야 해요");
  if (!G.inv.ring) return toast("약속의 반지가 필요해요 (상점)");
  const sworn = G.roster.filter((x) => x !== u && x.loveStage >= 5);
  if (sworn.length && harmony() < 60) {
    return playScene({ bg: "dusk", uid: u.id, lines: [[u.name, "반지는… 아직 못 받아요."], [u.name, `${sworn[0].name} 씨가 웃으면서 축하해 줄 수 있을 때, 그때 다시 물어봐 줘요.`], ["*", `연인들 사이가 화목해야 서약할 수 있어요 (지금 ${harmony()} / 필요 60).`]] }, () => { showHub(); showDetail(u); });
  }
  G.inv.ring--; u.loveStage = 5;
  if (sworn.length) addHarmony(5);
  save();
  playLoveScenes([[u, 5]], () => { save(); showHub(); showDetail(u); });
}

