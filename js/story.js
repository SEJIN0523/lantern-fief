// 하루가 시작될 때 볼 장면
function dayEvents() {
  const out = [];
  const once = (id, cond) => { if (cond && !G.seen[id]) { G.seen[id] = true; out.push(id); } };
  if (G.chapter === 1) {
    once("garen", G.day >= 2);
    once("guildtip", G.day >= 3);
    once("tax", G.day >= 8);
    if (G.day >= 20 && G.seen.tax && !G.seen.taxdone) {
      G.seen.taxdone = true;
      if (G.res.gold >= 150) { G.res.gold -= 150; out.push("taxpaid"); G.morale = Math.min(100, G.morale + 10); }
      else { G.res.food = Math.round(G.res.food * 0.5); G.res.wood = Math.round(G.res.wood * 0.5); G.res.gold = 0; G.morale = Math.max(0, G.morale - 20); out.push("taxfail"); }
    }
    once("ch1late", G.day > 30 && !G.flags.ch1clear);
  }
  return out;
}

// 장면 부수효과
function sceneEffect(id) {
  if (id === "garen") {
    const u = newUnit({ job: "warrior", slot: 0, name: "가렌", lv: 3, traits: { personality: "brave", hobby: "drink", origin: "fallen", quirk: null } });
    ensureProfile(u);
    u.wage = 1;
    G.roster.push(u); autoForm(u.id);
  }
  if (id === "ch1late") G.morale = Math.max(0, G.morale - 10);
  if (id === "ch1clear") {
    const h = heroU();
    promote(h, "tactician");
    G.inv.carkey = 1;
  }
}

